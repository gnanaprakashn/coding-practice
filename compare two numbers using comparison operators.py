# compare two numbers using comparison operators
def compare_numbers(a,b):
    print(f"{a} < {b} is {a < b}")
    print(f"{a} <= {b} is {a <= b}")
    print(f"{a} > {b} is {a > b}")
    print(f"{a} >= {b} is {a >= b}")
    print(f"{a} == {b} is {a == b}")
    print(f"{a} != {b} is {a != b}")


compare_numbers(a, b)
